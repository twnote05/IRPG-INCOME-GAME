// ---------- hero poses ----------
// Frames are computed from the standing sprites by shifting body parts, so every gear layer follows the
// body for free (no stored frames). Hero grid: head rows < 19, upper body < 28, legs below.
export interface Frame {
  up?: number; head?: number; all?: number; dx?: number // body offsets (upper body, head, everything, sideways)
  hx?: number; hy?: number                              // extra offset for the held weapon / off-hand
  step?: 'l' | 'r'                                      // lift one foot (walk)
  sit?: boolean; blink?: boolean; sweat?: number
}
export type Pose = 'still' | 'idle' | 'tired' | 'sit' | 'cheer' | 'attack' | 'hurt' | 'walk'
export const POSES: Record<Pose, { dur: number; frames: Frame[] }> = {
  still: { dur: 1, frames: [{}] },
  idle: { dur: 2.4, frames: [{}, {}, { up: 1 }, { up: 1, blink: true }] },              // breathe + blink
  tired: { dur: 1.6, frames: [{ up: 1, head: 1, sweat: 0 }, { up: 2, head: 1, sweat: 1, blink: true }] }, // slumped, sweating
  sit: { dur: 2.2, frames: [{ up: 6, head: 1, sit: true, sweat: 0, blink: true }, { up: 7, head: 1, sit: true, sweat: 1, blink: true }] }, // sat down, exhausted
  cheer: { dur: 0.9, frames: [{}, { all: -3 }, { all: -2 }] },                         // hop
  attack: { dur: 0.6, frames: [{ hy: -3 }, { up: -1, hy: -5 }, { dx: 1, hx: 3, hy: 2 }, { hx: 1, hy: 1 }] }, // raise, swing, follow through
  hurt: { dur: 0.3, frames: [{ dx: -1, blink: true }, { dx: 1 }] },                    // knocked back
  walk: { dur: 0.5, frames: [{ step: 'l' }, { all: -1 }, { step: 'r' }, { all: -1 }] },
}
const HEAD_END = 19, LEGS_START = 28

/**
 * One frame of a hero layer. `held` = weapon/off-hand (moves with the arms as a whole),
 * `base` = the body sprite (gets blink + sweat).
 */
export function poseRows(rows: string[], f: Frame, held = false, base = false) {
  const H = rows.length, W = rows[0].length
  const g = Array.from({ length: H }, () => Array<string>(W).fill('.'))
  const set = (x: number, y: number, c: string) => { if (c !== '.' && y >= 0 && y < H && x >= 0 && x < W) g[y][x] = c }
  const all = f.all ?? 0, up = f.up ?? 0, head = f.head ?? 0, dx = f.dx ?? 0
  rows.forEach((r, y) => [...r].forEach((c, x0) => {
    const x = x0 + dx
    if (held) return set(x + (f.hx ?? 0), y + all + up + (f.hy ?? 0), c)
    if (y < LEGS_START) return set(x, y + all + up + (y < HEAD_END ? head : 0), c)
    if (!f.sit) return set(x, y + all - (f.step && y >= 33 && (f.step === 'l') === (x0 < W / 2) ? 1 : 0), c)
    // sitting (front view): hips drop with the body, shins fold out of sight, feet splay outwards
    if (y <= 31) set(x, y + up, c)
    else if (y >= 38) set(x + (x < W / 2 ? -3 : 3), y, c)
  }))
  if (base) {
    const eyeY = 12 + all + up + head
    if (f.blink) { set(10 + dx, eyeY, 'N'); set(13 + dx, eyeY, 'N') }
    if (f.sweat !== undefined) { const y = 8 + up + head + f.sweat; set(18 + dx, y, 'W'); set(18 + dx, y + 1, 'c'); set(17 + dx, y + 1, 'c') }
  }
  return g.map(r => r.join(''))
}

