/** The context-specific advice line under an asset alert. */
export const alertTip = (t: Dict, a: AssetAlert): string =>
  a.kind === 'short' ? t.alerts.short(a.pct < 0, `${Math.abs(a.pct).toFixed(1)}%`)
    : a.kind === 'heavy' ? t.alerts.heavy
    : a.kind === 'stale' ? t.alerts.stale(a.asset.category !== 'Bond')
    : t.alerts.tips[a.kind][a.asset.category]
export type Lang = keyof typeof DICT
